impl FromStr for Language {
    type Err = String;

    fn from_str(s: &str) -> std::result::Result<Self, Self::Err> {
        match s {
            "auto" => Ok(Self::Auto),
            "zh_cn" | "zh-CN" | "ZH" => Ok(Self::ZhCn),
            "zh_tw" | "zh-TW" | "zh-Hant" => Ok(Self::ZhTw),
            "en" | "EN" => Ok(Self::En),
            "ja" | "JA" => Ok(Self::Ja),
            "ko" | "KO" => Ok(Self::Ko),
            "fr" | "FR" => Ok(Self::Fr),
            "es" | "ES" => Ok(Self::Es),
            "de" | "DE" => Ok(Self::De),
            "ru" | "RU" => Ok(Self::Ru),
            "it" | "IT" => Ok(Self::It),
            "pt" | "PT" | "pt_br" | "pt-BR" => Ok(Self::Pt),
            "tr" | "TR" => Ok(Self::Tr),
            "ar" | "AR" => Ok(Self::Ar),
            "vi" | "VI" => Ok(Self::Vi),
            "th" | "TH" => Ok(Self::Th),
            "id" | "ID" => Ok(Self::Id),
            "ms" | "MS" => Ok(Self::Ms),
            "hi" | "HI" => Ok(Self::Hi),
            "mn" | "MN" => Ok(Self::Mn),
            "no" | "NO" => Ok(Self::No),
            "nb" | "NB" => Ok(Self::Nb),
            "fa" | "FA" => Ok(Self::Fa),
            "uk" | "UK" => Ok(Self::Uk),
            "pl" | "PL" => Ok(Self::Pl),
            "nl" | "NL" => Ok(Self::Nl),
            "ro" | "RO" => Ok(Self::Ro),
            "cs" | "CS" => Ok(Self::Cs),
            "hu" | "HU" => Ok(Self::Hu),
            "el" | "EL" => Ok(Self::El),
            _ => Err(format!("Unknown language code: {}", s)),
        }
    }
}
